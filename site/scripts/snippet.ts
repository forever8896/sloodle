// Writes src/generated/course-snippet.ts: the app's demo course exported exactly as "Share this course as a file" does
// (src/demo.ts), checked against the real schema (sidecar/src/formats.ts), then trimmed for the page.
// Run with bun from site/: bun scripts/snippet.ts
import { writeFileSync } from "node:fs";

(globalThis as { location?: URL }).location = new URL("http://localhost/?demo");
const { demoRpc } = await import("../../src/demo");
const { courseSchema } = await import("../../sidecar/src/formats");

const file = (await demoRpc("course.export", { courseId: "demo" })) as { fileName: string; json: string };
const course = courseSchema.parse(JSON.parse(file.json));

const module = course.modules[0]!;
const objective = module.objectives.find((o) => o.lesson.blocks.length > 0) ?? module.objectives[0]!;
const blocks = objective.lesson.blocks.slice(0, 2);
const more = (n: number, what: string) => `… ${n} more ${n === 1 ? what : `${what}s`}`;

const trimmed = {
  format: course.format,
  version: course.version,
  id: course.id,
  title: course.title,
  subject: course.subject,
  summary: course.summary,
  modules: [
    {
      id: module.id,
      title: module.title,
      why: module.why,
      objectives: [
        {
          id: objective.id,
          statement: objective.statement,
          level: objective.level,
          lesson: {
            keyIdeas: objective.lesson.keyIdeas.slice(0, 1),
            blocks: [...blocks, more(objective.lesson.blocks.length - blocks.length, "block")],
          },
        },
        more(module.objectives.length - 1, "objective"),
      ],
    },
    more(course.modules.length - 1, "module"),
  ],
};

const json = JSON.stringify(trimmed, null, 2).replace(/"(… [^"]+)"/g, "$1");
writeFileSync(
  new URL("../src/generated/course-snippet.ts", import.meta.url),
  `// Generated by scripts/snippet.ts from the app's demo course (src/demo.ts), validated with sidecar/src/formats.ts.\nexport const courseFileName = ${JSON.stringify(file.fileName)};\nexport const courseSnippet = ${JSON.stringify(json)};\n`,
);
console.log(file.fileName, json.length, "chars");
console.log(json);
